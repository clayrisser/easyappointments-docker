#!/bin/sh

set -e

# A newline in TZ would inject further directives into the ini file, and
# `auto_prepend_file` is one of them, so accept only the characters real zone
# identifiers use (America/New_York, Etc/GMT+5, UTC). Everything else — ';',
# '=', whitespace, newlines — cannot survive this filter.
_tz="${TZ:-UTC}"
case "$_tz" in
'' | *[!A-Za-z0-9_/+-]*)
	echo "docker-entrypoint.sh: TZ '$_tz' is not a valid timezone identifier; using UTC" >&2
	_tz=UTC
	;;
esac

# PHP needs an explicit date.timezone; honour the standard TZ env var.
printf 'date.timezone = %s\n' "$_tz" \
	>/usr/local/etc/php/conf.d/timezone.ini

# config.php is written from a *quoted* heredoc, so the shell substitutes
# nothing into it: the file is byte-for-byte the same whatever the environment
# holds. PHP then reads the settings back out of the process environment at
# runtime, which is the property that matters — no environment value is ever
# parsed as PHP. Interpolating them here would make every variable a code
# injection vector, and escaping is not a fix: passwords may legally contain
# quotes, and a value that closes the string literal can append statements that
# run at file scope on every request.
cat >/var/www/html/config.php <<'EOF'
<?php

/**
 * Generated by docker-entrypoint.sh — do not edit.
 *
 * Deliberately free of interpolated values. Configuration is read from the
 * environment at runtime so that no environment value is ever parsed as PHP.
 */
(static function (): void {
    $string = static fn(string $name, string $default = ''): string => (($value = getenv($name)) === false ? $default : $value);

    // Accepts the spellings the shell-generated config used to allow; anything
    // else is false rather than a syntax error.
    $bool = static fn(string $name, bool $default): bool => (($value = getenv($name)) === false || $value === ''
        ? $default
        : in_array(strtolower(trim($value)), ['1', 'true', 'on', 'yes'], true));

    define('EA_BASE_URL', $string('BASE_URL', 'http://localhost'));
    define('EA_LANGUAGE', $string('LANGUAGE', 'english'));
    // DEBUG is the legacy name for DEBUG_MODE — keep accepting it.
    define('EA_DEBUG_MODE', getenv('DEBUG_MODE') === false ? $bool('DEBUG', false) : $bool('DEBUG_MODE', false));
    define('EA_DB_HOST', $string('DB_HOST', 'mariadb'));
    define('EA_DB_NAME', $string('DB_NAME', 'easyappointments'));
    define('EA_DB_USERNAME', $string('DB_USERNAME', 'easyappointments'));
    define('EA_DB_PASSWORD', $string('DB_PASSWORD', 'easyappointments'));
    define('EA_GOOGLE_SYNC_FEATURE', $bool('GOOGLE_SYNC_FEATURE', false));
    define('EA_GOOGLE_CLIENT_ID', $string('GOOGLE_CLIENT_ID'));
    define('EA_GOOGLE_CLIENT_SECRET', $string('GOOGLE_CLIENT_SECRET'));
})();

class Config
{
    // ------------------------------------------------------------------------
    // GENERAL SETTINGS
    // ------------------------------------------------------------------------

    const BASE_URL = EA_BASE_URL;
    const LANGUAGE = EA_LANGUAGE;
    const DEBUG_MODE = EA_DEBUG_MODE;

    // ------------------------------------------------------------------------
    // DATABASE SETTINGS
    // ------------------------------------------------------------------------

    const DB_HOST = EA_DB_HOST;
    const DB_NAME = EA_DB_NAME;
    const DB_USERNAME = EA_DB_USERNAME;
    const DB_PASSWORD = EA_DB_PASSWORD;

    // ------------------------------------------------------------------------
    // GOOGLE CALENDAR SYNC
    // ------------------------------------------------------------------------

    const GOOGLE_SYNC_FEATURE = EA_GOOGLE_SYNC_FEATURE;
    const GOOGLE_CLIENT_ID = EA_GOOGLE_CLIENT_ID;
    const GOOGLE_CLIENT_SECRET = EA_GOOGLE_CLIENT_SECRET;
}
EOF
chown www-data:www-data /var/www/html/config.php

exec "$@"
